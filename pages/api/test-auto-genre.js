import { createContentItem, validateContentData, createOrFindGenre } from '@/lib/upload-service';

export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  try {
    const { testType } = req.body;
    
    if (testType === 'validation') {
      // Test validation function
      const testCases = [
        {
          name: 'Traditional Upload',
          data: {
            title: 'Traditional Test',
            category: 'Blog',
            genreId: 1,
            coverImage: { data: 'test', filename: 'test.jpg', mimeType: 'image/jpeg' }
          }
        },
        {
          name: 'Auto-Genre Upload',
          data: {
            title: 'Auto-Genre Test',
            category: 'Blog',
            genreId: 578,
            genre: {
              id: 578,
              name: 'Software Testing',
              description: 'Testing methodology content',
              isAutoGenerated: true,
              confidence: 0.85,
              domain: 'Technical',
              createdBy: 'ContentRunway-LLM'
            },
            coverImage: { data: 'test', filename: 'test.jpg', mimeType: 'image/jpeg' }
          }
        },
        {
          name: 'Invalid Auto-Genre',
          data: {
            title: 'Invalid Test',
            category: 'Blog',
            genreId: 999,
            genre: {
              id: 'invalid',
              name: '',
              isAutoGenerated: true,
              confidence: 1.5
            },
            coverImage: { data: 'test', filename: 'test.jpg', mimeType: 'image/jpeg' }
          }
        }
      ];

      const results = testCases.map(testCase => ({
        name: testCase.name,
        validation: validateContentData(testCase.data)
      }));

      return res.status(200).json({ testType: 'validation', results });
    }

    if (testType === 'genre-creation') {
      // Test genre creation function
      const testGenre = {
        id: 999,
        name: 'Test Genre Auto-Creation',
        description: 'A test genre created automatically',
        isAutoGenerated: true,
        confidence: 0.9,
        domain: 'Test',
        createdBy: 'Test-System'
      };

      const result = await createOrFindGenre(testGenre);
      return res.status(200).json({ testType: 'genre-creation', result });
    }

    if (testType === 'duplicate-genre') {
      // Test duplicate genre handling (case-insensitive)
      const duplicateGenre = {
        id: 888,
        name: 'FULL TEST GENRE', // Different case
        description: 'Trying to create duplicate with different case',
        isAutoGenerated: true,
        confidence: 0.8,
        domain: 'Duplicate',
        createdBy: 'Test-Duplicate'
      };

      const result = await createOrFindGenre(duplicateGenre);
      return res.status(200).json({ testType: 'duplicate-genre', result });
    }

    if (testType === 'full-upload') {
      // Test full upload with auto-genre creation
      const testData = {
        title: 'Full Auto-Genre Upload Test',
        author: 'Test Author',
        category: 'Blog',
        genreId: 888,
        genre: {
          id: 888,
          name: 'Full Test Genre',
          description: 'A genre created during full upload test',
          isAutoGenerated: true,
          confidence: 0.95,
          domain: 'Testing',
          createdBy: 'Test-System'
        },
        summary: 'Test summary for auto-genre functionality',
        content: 'Test content demonstrating auto-genre creation',
        coverImage: {
          data: 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==',
          filename: 'test.png',
          mimeType: 'image/png'
        }
      };

      const validation = validateContentData(testData);
      if (!validation.isValid) {
        return res.status(400).json({ error: 'Validation failed', details: validation.errors });
      }

      const result = await createContentItem(testData);
      return res.status(200).json({ testType: 'full-upload', result });
    }

    return res.status(400).json({ error: 'Invalid test type' });

  } catch (error) {
    console.error('Test API error:', error);
    return res.status(500).json({ error: error.message });
  }
}